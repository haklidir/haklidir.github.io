#!/usr/bin/env python3
"""Generate Hugo content from the YAML files in source/.

    python3 scripts/generate_content.py

Writes:
  content/publications/<slug>/index.md and cite.bib   (from source/publications.yaml)
  content/events/<slug>/index.md                     (from source/talks.yaml)
  content/research/<key>/index.md                    (from source/research_areas.yaml)
  content/events/_index.md (talks list + media)       (from source/media.yaml)

Generated files are rewritten on every run. To attach a PDF to a paper, put it
next to the generated index.md as content/publications/<slug>/<slug>.pdf; the
generator keeps extra files in publication folders and the page links the PDF.
See MAINTAINING.md.
"""

from __future__ import annotations

import datetime as dt
import re
import shutil
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "source"
CONTENT = ROOT / "content"

OWNER = "me"
OWNER_NAME = ("Mehmet", "Haklıdır")

# Surnames with more than one word (family name is not just the last token).
COMPOUND_FAMILY = ["Tut Haklıdır", "Pembe Muhtaroğlu", "Coskuner-Weber"]

GENERATED_MARK = "# generated by scripts/generate_content.py; edit source/*.yaml instead\n"


# --------------------------------------------------------------------------- helpers
def load(name: str):
    with open(SRC / name, encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def parse_date(value) -> tuple[dt.date, str]:
    """Return (date, precision) where precision is year|month|day."""
    if isinstance(value, dt.date):
        return value, "day"
    text = str(value).strip()
    if re.fullmatch(r"\d{4}", text):
        return dt.date(int(text), 1, 1), "year"
    if re.fullmatch(r"\d{4}-\d{2}", text):
        y, m = text.split("-")
        return dt.date(int(y), int(m), 1), "month"
    return dt.date.fromisoformat(text), "day"


def front_matter(data: dict, body: str = "") -> str:
    fm = yaml.safe_dump(data, allow_unicode=True, sort_keys=False, width=1000)
    out = "---\n" + GENERATED_MARK + fm + "---\n"
    if body.strip():
        out += "\n" + body.strip() + "\n"
    return out


def split_name(full: str) -> tuple[str, str]:
    if full == OWNER:
        return OWNER_NAME
    for fam in COMPOUND_FAMILY:
        if full.endswith(" " + fam):
            return full[: -len(fam) - 1], fam
    parts = full.split()
    if len(parts) == 1:
        return "", parts[0]
    return " ".join(parts[:-1]), parts[-1]


def bib_escape(text: str) -> str:
    return text.replace("&", r"\&").replace("%", r"\%").replace("_", r"\_")


def ascii_key(text: str) -> str:
    table = str.maketrans("çğıöşüÇĞİÖŞÜâîû", "cgiosuCGIOSUaiu")
    text = text.translate(table)
    return re.sub(r"[^a-z0-9]", "", text.lower())


def paragraphs(text: str) -> str:
    """Folded YAML (>-) keeps paragraph breaks as single newlines; make them Markdown breaks."""
    return "\n\n".join(line.strip() for line in text.strip().split("\n") if line.strip())


def slugify(text: str) -> str:
    table = str.maketrans("çğıöşüÇĞİÖŞÜâîû", "cgiosuCGIOSUaiu")
    return re.sub(r"[^a-z0-9]+", "-", text.translate(table).lower()).strip("-")


def first_sentence(text: str, limit: int = 260) -> str:
    text = re.sub(r"\*\*?([^*]+)\*\*?", r"\1", " ".join(text.split()))
    match = re.match(r"(.+?[.!?])(\s|$)", text)
    sentence = match.group(1) if match else text
    if len(sentence) > limit:
        sentence = sentence[: limit - 1].rsplit(" ", 1)[0] + "…"
    return sentence


def reset_generated_dir(path: Path, keep_extra_files: bool) -> None:
    """Remove generated files; optionally keep user-added files (PDFs, images)."""
    if not path.exists():
        return
    for child in path.iterdir():
        if child.is_dir():
            if keep_extra_files:
                for f in child.iterdir():
                    if f.name in ("index.md", "cite.bib"):
                        f.unlink()
                if not any(child.iterdir()):
                    child.rmdir()
            else:
                shutil.rmtree(child)


# --------------------------------------------------------------------------- research areas
def area_cards(areas: list[dict], pubs: list[dict]) -> list[dict]:
    """Items for the HugoBlox focus-areas block (home page and /research/)."""
    items = []
    for area in sorted(areas, key=lambda a: a["weight"]):
        count = sum(1 for p in pubs if area["key"] in p.get("areas", []))
        item = {
            "name": area["name"],
            "description": area["summary"],
            "icon": area.get("icon", "hero/light-bulb"),
            "url": f"/research/{area['key']}/",
            "topics": area.get("topics", []),
            "metrics": [{"icon": "hero/document-text", "value": str(count),
                         "label": "paper" if count == 1 else "papers"}],
            "cta": {"text": "Read more", "url": f"/research/{area['key']}/"},
        }
        items.append(item)
    return items


def refresh_home_cards(items: list[dict]) -> None:
    """Replace the items of the focus-areas block on the hand-written home page."""
    home = CONTENT / "_index.md"
    if not home.exists():
        return
    text = home.read_text(encoding="utf-8")
    _, fm_text, body = text.split("---\n", 2)
    fm = yaml.safe_load(fm_text)
    for section in fm.get("sections", []):
        if section.get("block") == "focus-areas":
            section.setdefault("content", {})["items"] = items
    note = "# Hand-edited page. The items of the focus-areas block are refreshed by scripts/generate_content.py.\n"
    dumped = yaml.safe_dump(fm, allow_unicode=True, sort_keys=False, width=1000)
    home.write_text("---\n" + note + dumped + "---\n" + body, encoding="utf-8")


def build_research(areas: list[dict], pubs: list[dict]) -> dict[str, dict]:
    out_dir = CONTENT / "research"
    reset_generated_dir(out_dir, keep_extra_files=False)
    out_dir.mkdir(parents=True, exist_ok=True)

    items = area_cards(areas, pubs)
    refresh_home_cards(items)
    index = {
        "title": "Research",
        "summary": "Research areas of Mehmet Haklıdır: agentic AI safety and governance, reinforcement "
                   "learning and autonomous systems, and applied AI for language, health and the geosciences.",
        "type": "landing",
        "sections": [
            {
                "block": "focus-areas",
                "content": {
                    "title": "Research",
                    "text": "My research spans agentic AI safety and governance, reinforcement learning for "
                            "autonomous systems, and applied AI for language, health and the geosciences. "
                            "Each area lists its publications.",
                    "items": items,
                },
                "design": {"layout": "cards"},
            }
        ],
    }
    (out_dir / "_index.md").write_text(front_matter(index), encoding="utf-8")

    for area in areas:
        if not re.fullmatch(r"[A-Za-z0-9 ]+", area["tag"]):
            sys.exit(f"research area {area['key']}: tag may only contain letters, digits and spaces")
        page_dir = out_dir / area["key"]
        page_dir.mkdir(parents=True, exist_ok=True)
        page = {
            "title": area["name"],
            "summary": area["summary"],
            "type": "landing",
            "sections": [
                {
                    "block": "markdown",
                    "content": {"title": area["name"], "text": area["narrative"]},
                    "design": {"columns": "1"},
                },
                {
                    "block": "collection",
                    "content": {
                        "title": "Publications",
                        "count": 0,
                        "filters": {"folders": ["publications"], "tag": area["tag"]},
                    },
                    "design": {"view": "citation"},
                },
            ],
        }
        (page_dir / "index.md").write_text(front_matter(page), encoding="utf-8")
    return {a["key"]: a for a in areas}


# --------------------------------------------------------------------------- publications
BIB_TYPES = {
    "article-journal": "article",
    "paper-conference": "inproceedings",
    "chapter": "incollection",
    "article": "misc",
}


def bibtex(pub: dict, year: int, used_keys: set) -> str:
    authors = " and ".join(
        f"{{{fam}}}, {given}" if " " in fam else f"{fam}, {given}" if given else fam
        for given, fam in (split_name(a) for a in pub["authors"])
    )
    first_family = split_name(pub["authors"][0])[1]
    first_word = next((w for w in re.findall(r"[A-Za-zÇĞİÖŞÜçğıöşü]+", pub["title"]) if len(w) > 3), "paper")
    key = base_key = f"{ascii_key(first_family)}{year}{ascii_key(first_word)}"
    suffix = iter("bcdefghijklmnopqrstuvwxyz")
    while key in used_keys:  # unique across the site so the files can be merged into one .bib
        key = base_key + next(suffix)
    used_keys.add(key)

    ptype = pub["type"]
    if ptype == "thesis":
        entry = "phdthesis" if "Ph.D." in pub.get("venue", "") else "mastersthesis"
    else:
        entry = BIB_TYPES.get(ptype, "misc")

    fields: list[tuple[str, str]] = [("title", "{" + bib_escape(pub["title"]) + "}"), ("author", authors)]
    venue = pub.get("venue")
    if ptype == "article-journal" and venue:
        fields.append(("journal", bib_escape(venue)))
    elif ptype in ("paper-conference", "chapter") and venue:
        fields.append(("booktitle", bib_escape(venue)))
    elif ptype == "thesis":
        fields.append(("school", bib_escape(pub.get("publisher", ""))))
    fields.append(("year", str(year)))
    for name, src in (("volume", "volume"), ("number", "issue"), ("pages", "pages")):
        if pub.get(src) is not None:
            fields.append((name, str(pub[src]).replace("-", "--")))
    if pub.get("publisher") and ptype != "thesis":
        fields.append(("publisher", bib_escape(pub["publisher"])))
    if pub.get("doi"):
        fields.append(("doi", pub["doi"]))
    if pub.get("arxiv"):
        fields += [("eprint", pub["arxiv"]), ("archivePrefix", "arXiv")]
    if pub.get("status"):
        fields.append(("note", "Forthcoming" if pub["status"] == "forthcoming" else pub["status"]))
    if pub.get("language"):
        fields.append(("language", {"tr": "turkish"}.get(pub["language"], pub["language"])))

    body = ",\n".join(f"  {k} = {{{v}}}" for k, v in fields)
    return f"@{entry}{{{key},\n{body}\n}}\n"


def build_publications(pubs: list[dict], areas: dict[str, dict]) -> None:
    out_dir = CONTENT / "publications"
    reset_generated_dir(out_dir, keep_extra_files=True)
    out_dir.mkdir(parents=True, exist_ok=True)

    groups = [
        ("article-journal", "Journal Articles"),
        ("paper-conference", "Conference and Workshop Papers"),
        ("chapter", "Book Chapters"),
        ("article", "Preprints"),
        ("thesis", "Theses"),
    ]
    counts = {t: sum(1 for p in pubs if p["type"] == t) for t, _ in groups}
    intro = (
        f"{len(pubs)} publications: {counts['article-journal']} journal articles, "
        f"{counts['paper-conference']} conference and workshop papers, {counts['chapter']} book chapters"
        + (f", {counts['article']} preprint" + ("s" if counts["article"] != 1 else "") if counts["article"] else "")
        + f" and {counts['thesis']} theses. Each title opens a page with publication details, "
        "links and a BibTeX citation.\n\n"
        "Also on [Google Scholar](https://scholar.google.com/citations?user=sEOFMPoAAAAJ), "
        "[ORCID](https://orcid.org/0000-0003-4985-1116), "
        "[Scopus](https://www.scopus.com/authid/detail.uri?authorId=25929922600) and "
        "[ResearchGate](https://www.researchgate.net/profile/Mehmet-Haklidir)."
    )
    sections = [{"block": "markdown", "content": {"title": "Publications", "text": intro},
                 "design": {"columns": "1"}}]
    for ptype, heading in groups:
        if not counts[ptype]:
            continue
        sections.append({
            "block": "collection",
            "id": ptype,
            "content": {
                "title": heading,
                "count": 0,
                "filters": {"folders": ["publications"], "publication_type": ptype},
                "archive": {"enable": False},
            },
            "design": {"view": "citation"},
        })
    index = {
        "title": "Publications",
        "summary": "Journal articles, conference papers, book chapters and theses by Mehmet Haklıdır.",
        "type": "landing",
        "sections": sections,
    }
    (out_dir / "_index.md").write_text(front_matter(index), encoding="utf-8")

    seen = set()
    used_keys: set = set()
    for pub in pubs:
        slug = pub["slug"]
        if slug in seen:
            sys.exit(f"duplicate slug: {slug}")
        seen.add(slug)
        for key in pub.get("areas", []):
            if key not in areas:
                sys.exit(f"{slug}: unknown research area '{key}'")

        date, precision = parse_date(pub["date"])
        page_dir = out_dir / slug
        page_dir.mkdir(parents=True, exist_ok=True)

        publication = {"name": pub.get("venue", "")}
        for src, dst in (("venue_short", "short_name"), ("volume", "volume"), ("issue", "issue"),
                         ("pages", "pages"), ("publisher", "publisher")):
            if pub.get(src) is not None:
                publication[dst] = pub[src]

        ids = {k: pub[k] for k in ("doi", "arxiv", "acl_id") if pub.get(k)}
        links = []
        local_pdf = page_dir / f"{slug}.pdf"
        if pub.get("pdf") and not local_pdf.exists():
            links.append({"type": "pdf", "url": pub["pdf"]})
        if pub.get("url"):
            links.append({"type": "site", "url": pub["url"]})

        summary_src = pub.get("overview") or pub.get("abstract") or ""
        fm = {
            "title": pub["title"],
            "authors": pub["authors"],
            "date": date.isoformat(),
            "date_precision": precision,
            "publication_types": [pub["type"]],
            "publication": publication,
        }
        if pub.get("abstract"):
            fm["abstract"] = paragraphs(pub["abstract"])
        if pub.get("summary"):
            fm["summary"] = pub["summary"]
        elif summary_src:
            fm["summary"] = first_sentence(summary_src)
        if pub.get("open_access"):
            fm["open_access"] = True
        fm["tags"] = [areas[k]["tag"] for k in pub.get("areas", [])]
        fm["featured"] = bool(pub.get("featured", False))
        if ids:
            fm["hugoblox"] = {"ids": ids}
        if links:
            fm["links"] = links
        if pub.get("award"):
            fm["awards"] = [{"name": pub["award"], "level": "winner"}]
        for key in ("status", "language", "title_en"):
            if pub.get(key):
                fm[f"pub_{key}"] = pub[key]
        fm["reading_time"] = False
        fm["show_date_updated"] = False

        body = []
        if pub.get("title_en"):
            body.append(f"*English title: {pub['title_en']}*")
        if pub.get("status") == "forthcoming":
            body.append("> [!NOTE]\n> Accepted for publication; forthcoming.")
        if pub.get("overview"):
            body.append(paragraphs(pub["overview"]))
        if pub.get("note"):
            body.append(pub["note"].strip())
        area_links = ", ".join(f"[{areas[k]['name']}](/research/{k}/)" for k in pub.get("areas", []))
        if area_links:
            body.append(f"Research area: {area_links}.")

        (page_dir / "index.md").write_text(front_matter(fm, "\n\n".join(body)), encoding="utf-8")
        (page_dir / "cite.bib").write_text(bibtex(pub, date.year, used_keys), encoding="utf-8")


# --------------------------------------------------------------------------- talks & media
def fmt_date(value) -> str:
    if value is None:
        return ""
    date, precision = parse_date(value)
    return str(date.year) if precision == "year" else date.strftime("%B %Y")


def media_sections(media: dict) -> list[dict]:
    """Two media-grid blocks (layouts/_partials/hbx/blocks/media-grid/) for videos and press."""
    sections = []
    videos = []
    for v in media.get("videos", []):
        item = {"title": v["title"], "video": True,
                "kicker": " · ".join(x for x in (v.get("channel", ""), fmt_date(v.get("date"))) if x)}
        if v.get("youtube"):
            item["url"] = f"https://www.youtube.com/watch?v={v['youtube']}"
            item["image"] = f"https://i.ytimg.com/vi/{v['youtube']}/hqdefault.jpg"
        elif v.get("url"):
            item["url"] = v["url"]
        if v.get("image"):
            item["image"] = v["image"]
        videos.append(item)
    if videos:
        sections.append({"block": "media-grid", "id": "media-videos",
                         "content": {"title": "TV and Video", "items": videos}})

    press = []
    for p in sorted(media.get("press", []), key=lambda x: str(x["date"]), reverse=True):
        item = {"title": p["title"], "kicker": f"{p['outlet']} · {fmt_date(p['date'])}"}
        if p.get("url") or p.get("full"):
            item["url"] = p.get("url") or p["full"]
        if p.get("image"):
            item["image"] = p["image"]
        press.append(item)
    if press:
        sections.append({"block": "media-grid", "id": "media-press",
                         "content": {"title": "Press", "items": press}})
    return sections


def build_events(talks: list[dict], media: dict) -> None:
    out_dir = CONTENT / "events"
    reset_generated_dir(out_dir, keep_extra_files=False)
    out_dir.mkdir(parents=True, exist_ok=True)

    index = {
        "title": "Talks & Media",
        "summary": "Invited talks, keynotes, panels, TV appearances and press coverage of Mehmet Haklıdır.",
        "type": "landing",
        "sections": [
            {
                "block": "collection",
                "id": "talks",
                "content": {
                    "title": "Talks",
                    "text": "Invited talks, keynotes and panels; recordings are linked where available. "
                            "See also [TV and video](#media-videos) and [press coverage](#media-press).",
                    "count": 0,
                    "filters": {"folders": ["events"]},
                    "archive": {"enable": False},
                },
                "design": {"view": "date-title-summary"},
            },
            *media_sections(media),
        ],
    }
    (out_dir / "_index.md").write_text(front_matter(index), encoding="utf-8")

    used = set()
    for talk in talks:
        date, precision = parse_date(talk["date"])
        event_slug = slugify(talk["event"])
        if len(event_slug) > 48:
            event_slug = event_slug[:48].rsplit("-", 1)[0]
        base = f"{date.year}-{event_slug or 'talk'}"
        slug = base
        n = 2
        while slug in used:
            slug = f"{base}-{n}"
            n += 1
        used.add(slug)

        summary_bits = [talk.get("role", "Talk")]
        summary_bits.append(talk["event"])
        if talk.get("location"):
            summary_bits.append(talk["location"])
        if talk.get("youtube"):
            summary_bits.append("Video")
        fm = {
            "title": talk["title"],
            "event_name": talk["event"],
            "date": date.isoformat(),
            "date_precision": precision,
            "all_day": True,
            "authors": [OWNER],
            "summary": " · ".join(summary_bits),
            "talk_role": talk.get("role", ""),
            "reading_time": False,
            "show_date_updated": False,
        }
        if talk.get("location"):
            fm["location"] = talk["location"]
        links = []
        if talk.get("youtube"):
            links.append({"type": "video", "url": f"https://www.youtube.com/watch?v={talk['youtube']}"})
        if talk.get("url"):
            links.append({"type": "site", "url": talk["url"]})
        if links:
            fm["links"] = links

        body = []
        meta = []
        if talk.get("organizer"):
            meta.append(f"Organized by {talk['organizer']}.")
        meta.append({"tr": "Talk given in Turkish.", "en": "Talk given in English."}.get(talk.get("language", ""), ""))
        body.append(" ".join(m for m in meta if m))
        if talk.get("youtube"):
            body.append(f"{{{{< youtube {talk['youtube']} >}}}}")
        page_dir = out_dir / slug
        page_dir.mkdir(parents=True, exist_ok=True)
        (page_dir / "index.md").write_text(front_matter(fm, "\n\n".join(body)), encoding="utf-8")


def main() -> None:
    pubs = load("publications.yaml")
    areas = build_research(load("research_areas.yaml"), pubs)
    build_publications(pubs, areas)
    talks = load("talks.yaml")
    build_events(talks, load("media.yaml"))
    print(f"Generated {len(pubs)} publications, {len(talks)} talks, {len(areas)} research areas.")


if __name__ == "__main__":
    main()
